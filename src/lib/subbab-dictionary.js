/**
 * Mencocokkan teks judul/tag bebas ke kunci kanonikal sub-bab
 * @param {string} text - Judul atau tag sub-bab
 * @returns {string|null} - Tag kanonikal (misal: "latar_belakang", "rumusan_masalah", dll)
 */
export function matchSubBabTag(text) {
  if (!text || typeof text !== "string") return null;
  const clean = text
    .toLowerCase()
    .replace(/[^\w\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  // 1. Coba exact match ke salah satu variasi
  for (const [canonicalTag, variations] of Object.entries(SUBBAB_DICTIONARY)) {
    for (const variation of variations) {
      const normVar = variation.toLowerCase().trim();
      if (clean === normVar || clean.includes(normVar) || normVar.includes(clean)) {
        return canonicalTag;
      }
    }
  }

  // 2. Normalisasi snake_case langsung jika cocok dengan kunci
  const snake = clean.replace(/\s+/g, "_");
  if (SUBBAB_DICTIONARY[snake]) {
    return snake;
  }

  return null;
}

